            "CONVERSATIONAL_PREFIXES = [\"Hey MJ,\", \"Jarvis,\", \"Could you please\", \"I need you to\", \"Would you mind to\"]\n",
            "TYPO_MAP = {\"youtube\": [\"youtub\", \"yutube\", \"yt\"], \"google\": [\"gogle\", \"googel\"], \"search\": [\"serch\", \"srch\"], \"python\": [\"pytn\", \"pyton\"]}\n",
            "\n",
            "augmented_dataset = []\n",
            "\n",
            "def augment_prompt(text):\n",
            "    variants = []\n",
            "    words = text.split()\n",
            "    variants.append(f\"{random.choice(INDIAN_ENGLISH_PREFIXES)} {text}\")\n",
            "    variants.append(f\"{random.choice(CONVERSATIONAL_PREFIXES)} {text.lower()}\")\n",
            "    typo_words = [random.choice(TYPO_MAP[w.lower()]) if w.lower() in TYPO_MAP else w for w in words]\n",
